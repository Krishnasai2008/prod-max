"""
Give every folder under docs/ an index.md overview page (and docs/ itself
a homepage): subfolders as clickable cards, notes as a compact card grid.

Run from the project root:  python make_indexes.py
Safe to re-run: regenerates only the index pages it made itself (marked
containing MARK), never one you wrote; skips folders with a README.md.

Folder titles come from a `title:` line in the folder's .nav.yml (the same
file the sidebar reads), so cards, page titles and the sidebar always agree.
A folder that only wraps one subfolder (e.g. ai-ml/ -> output/) lists that
subfolder's contents directly; its .nav.yml should hoist it in the sidebar too.
"""
import re
from datetime import date
from pathlib import Path

DOCS = Path("docs")
MARK = "<!-- auto-generated by make_indexes.py; delete this line to keep your edits -->"
SKIP = {"stylesheets", "javascripts", "assets", "images", "img"}
NOT_NOTES = ("index.md", "readme.md")
PAGES = {"stats.md"}  # pages under docs/ that are not notes (javascripts/pmstats.js draws /stats/)
FOLDER_ICON = "material-folder-outline"
RECENT = 6  # notes listed under "Recently added" on the home page
ADDED = re.compile(r"_?Added:? (\d{4}-\d{2}-\d{2})")  # "_Added: 2026-10-24_", or "Added 2026-10-24" after tidy_markdown.py
ICONS = {  # subject folder name -> icon on its home-page card (any Material icon; others get a folder)
    "example": "material-book-open-variant", "operating-systems": "material-linux",
    "computer-networks": "material-lan", "discrete-math": "material-graph-outline",
    "python": "material-language-python",
}


def notes_in(folder: Path, recursive=False) -> list[Path]:
    files = folder.rglob("*.md") if recursive else folder.glob("*.md")
    return sorted(f for f in files if f.name.lower() not in NOT_NOTES and f.relative_to(DOCS).as_posix() not in PAGES
                  and not any(p.startswith(".") or p in SKIP for p in f.relative_to(DOCS).parts))


def visible(d: Path) -> bool:
    return d.is_dir() and d.name not in SKIP and not d.name.startswith(".") and bool(notes_in(d, True))


def subdirs_of(folder: Path) -> list[Path]:
    return sorted(d for d in folder.iterdir() if visible(d))


def unwrap(folder: Path) -> Path:
    """Follow folders that hold no notes of their own and exactly one subfolder."""
    while not notes_in(folder) and not (folder / "README.md").exists() and len(subdirs_of(folder)) == 1:
        folder = subdirs_of(folder)[0]
    return folder


def title_of(md: Path) -> str:
    try:
        for line in md.read_text(encoding="utf-8").splitlines():
            if line.startswith("# "):
                return line[2:].strip()
    except UnicodeDecodeError:
        pass
    return pretty(md.stem)


def added_on(md: Path) -> str:
    """Newest "Added" date in a note ("" if none)."""
    try:
        return max(ADDED.findall(md.read_text(encoding="utf-8")), default="")
    except UnicodeDecodeError:
        return ""


assert ADDED.findall("_Added: 2026-10-24_ Added 2026-10-23\n{ .added }") == ["2026-10-24", "2026-10-23"]


def folder_title(d: Path) -> str:
    nav = d / ".nav.yml"
    if nav.exists():
        m = re.search(r"^title:\s*(.+?)\s*$", nav.read_text(encoding="utf-8"), re.M)
        if m:
            return m.group(1).strip("\"'")
    return pretty(d.name)


def pretty(name: str) -> str:
    # same rule the sidebar uses for folders without a .nav.yml title
    name = name.replace("-", " ").replace("_", " ")
    return name[:1].upper() + name[1:]


def link(target: str) -> str:
    return "<" + target + ">" if " " in target else target  # paths with spaces need <...>


def plural(n: int, word: str) -> str:
    return f"{n} {word}{'' if n == 1 else 's'}"


written = 0
folders = [DOCS] + sorted(p for p in DOCS.rglob("*") if p.is_dir())
for folder in folders:
    rel = folder.relative_to(DOCS).parts
    if any(part.startswith(".") or part in SKIP for part in rel) or not notes_in(folder, True):
        continue
    index = folder / "index.md"
    if (folder / "README.md").exists():
        continue
    if index.exists() and MARK not in index.read_text(encoding="utf-8"):
        continue  # hand-written index: leave it alone

    content = folder if folder == DOCS else unwrap(folder)
    prefix = "" if content == folder else content.relative_to(folder).as_posix() + "/"
    subdirs = subdirs_of(content)
    notes = notes_in(content)
    if (content / "README.md").exists() and content != folder:
        notes = [content / "README.md"] + notes  # a hoisted wrapper's README is a real note

    if folder == DOCS:
        lines = ["---", "hide:", "  - navigation", "  - toc", "---", MARK, "",  # front matter must come first
                 "# My Notes", "",
                 f"{plural(len(subdirs), 'subject')} · {plural(len(notes_in(DOCS, True)), 'note')} "
                 "· press ++slash++ to search", "{ .subtitle }", "",
                 '<div class="study-continue" hidden></div>', "",  # filled by javascripts/study.js
                 '<div class="study-today"></div>', "",  # to-do list, filled by javascripts/today.js
                 '<div class="study-plan"></div>', ""]  # pm's plan and due reviews, filled by javascripts/pmhome.js
    else:
        lines = ["---", "hide:", "  - toc", "---", MARK, f"# {folder_title(folder)}", "",
                 f"{plural(len(notes_in(folder, True)), 'note')}", "{ .subtitle }", "",
                 f'<div class="study-progress" data-total="{len(notes_in(folder, True))}"></div>', ""]

    if subdirs:
        lines += ["## Subjects" if folder == DOCS else "## Sections", "", '<div class="grid cards" markdown>', ""]
        for d in subdirs:
            entry = "README.md" if (d / "README.md").exists() else "index.md"
            icon = ICONS.get(d.name, FOLDER_ICON) if folder == DOCS else FOLDER_ICON
            lines += [f"-   :{icon}:{{ .lg .middle }} __[{folder_title(d)}]({link(prefix + d.name + '/' + entry)})__",
                      "", f"    {plural(len(notes_in(d, True)), 'note')}", ""]
        lines += ["</div>", ""]
    if notes:
        lines += ["## Notes", "", '<div class="grid cards compact" markdown>', ""]
        lines += [f"-   :material-file-document-outline: [{title_of(f)}]({link(prefix + f.name)})" for f in notes]
        lines += ["", "</div>", ""]

    if folder == DOCS:  # study stats (javascripts/today.js), then "Recently added" last, both folded away until clicked
        lines += ['<div class="study-stats"></div>', ""]
        recent = [r for r in sorted(((added_on(f), f) for f in notes_in(DOCS, True)), reverse=True)[:RECENT] if r[0]]
        if recent:
            lines += ['<details class="study-recent" markdown>', "<summary>Recently added</summary>", "",
                      '<div class="grid cards compact" markdown>', ""]
            for day, f in recent:
                d = date.fromisoformat(day)
                where = folder_title(DOCS / f.relative_to(DOCS).parts[0])
                lines += [f"-   :material-new-box: [{title_of(f)}]({link(f.relative_to(DOCS).as_posix())})",
                          "", f"    <small>{where} · {d.day} {d:%b %Y}</small>", ""]
            lines += ["</div>", "", "</details>", ""]

    text = "\n".join(lines)
    if not index.exists() or index.read_text(encoding="utf-8") != text:
        index.write_text(text, encoding="utf-8")
        written += 1

print(f"Wrote {written} index.md files")
